def localize_text(text, language):
    if language!='kk' or not isinstance(text,str): return text
    if text in TEXT: return TEXT[text]
    for source in sorted(TEXT,key=len,reverse=True):
        text=text.replace(source,TEXT[source])
    return text


def localize_response(response, language):
    if language!='kk': return response
    result=copy.deepcopy(response)
    def product(value):
        if not isinstance(value,dict): return
        value['warnings']=[localize_text(w,language) for w in value.get('warnings',[])]
        if value.get('analogue_reason'): value['analogue_reason']=localize_text(value['analogue_reason'],language)
    if 'text' in result: result['text']=localize_text(result['text'],language)
    for key in ('warnings','suggestions'):
        if key in result: result[key]=[localize_text(text,language) for text in result[key]]
    for source in result.get('sources',[]): source['title']=localize_text(source['title'],language)
    for value in result.get('products',[]): product(value)
    if result.get('proposal'): product(result['proposal'].get('product'))
    if result.get('cart'):
        result['cart']['notice']=localize_text(result['cart'].get('notice',''),language)
        for item in result['cart'].get('items',[]): product(item.get('product'))
    if result.get('integrations'):
        result['integrations']['notice']=localize_text(result['integrations'].get('notice',''),language)
    return result
